export type Movie = {
  mediaType: "movie" | "episode" | "unclassified";
  seriesId?: string;
  showTitle?: string;
  seasonNumber?: number;
  episodeNumber?: number;
  episodeEnd?: number;
  id: string;
  certification: string | null;
  trailers: { name: string; url: string }[];
  tmdbId: number | null;
  title: string;
  year: number | null;
  overview: string | null;
  genres: string[];
  cast: string[];
  director: string | null;
  rating: number | null;
  duration: number;
  width: number;
  height: number;
  videoCodec: string | null;
  audioCodec: string | null;
  container: string;
  poster: string | null;
  backdrop: string | null;
  available: boolean;
  review: boolean;
  addedAt: number;
  position: number;
  completed: boolean;
  watchlisted: boolean;
  collection: string | null;
  audioTracks: Track[];
  subtitles: Track[];
};
export type Track = {
  index: number;
  codec: string;
  language: string;
  title: string;
};
export type Profile = {
  id: string;
  name: string;
  avatar: string;
  child: boolean;
  locked: boolean;
};
export type Session = {
  user: { id: string; username: string };
  profileId: string | null;
  profiles: Profile[];
};
export type TVEpisode = Movie & {
  seriesId: string;
  showTitle: string;
  seasonNumber: number;
  episodeNumber: number;
  episodeEnd: number;
  episodeTitle: string;
  airDate: string | null;
  progressUpdatedAt: number;
};
export type TVShow = {
  id: string;
  title: string;
  year: number | null;
  overview: string | null;
  poster: string | null;
  backdrop: string | null;
  genres: string[];
  cast: string[];
  rating: number | null;
  certification: string | null;
  review: boolean;
  watchlisted: boolean;
  seasonCount: number;
  episodeCount: number;
  availableCount: number;
  completedCount: number;
  tmdbId: number | null;
};
export type TVSeason = {
  seriesId: string;
  number: number;
  name: string;
  overview: string | null;
  poster: string | null;
  episodes: TVEpisode[];
};
export type TVShowDetails = TVShow & {
  seasons: TVSeason[];
  resumeEpisode: TVEpisode | null;
};
